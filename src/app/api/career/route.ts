import { NextRequest, NextResponse } from 'next/server';
import { escapeHtml, getMailConfig, getMailer, renderSubmissionEmail } from '@/lib/mail';
import { getD1Client } from '@/lib/d1-client';
import { r2Client } from '@/lib/r2-client';
import { clean, clientAddress, emailPattern, rateLimited, verifyMathCaptcha } from '@/lib/form-security';

export const runtime = 'nodejs';

export async function POST(request: NextRequest) {
  try {
    const formData = await request.formData();
    
    // Extract form fields
    if (rateLimited(`career:${clientAddress(request)}`)) return NextResponse.json({ error: 'Too many submissions. Please try again later.' }, { status: 429 });
    const fullname = clean(formData.get('fullname'), 100);
    const email = clean(formData.get('email'), 254);
    const mobile = clean(formData.get('mobile'), 30);
    const city = clean(formData.get('city'), 100);
    const message = clean(formData.get('message'), 5000);
    const captcha = formData.get('captcha') as string;
    const captchaQuestion = clean(formData.get('captchaQuestion'), 30);
    const resume = formData.get('uploaded_file') as File | null;
    
    // Validate required fields
    if (!fullname || !email || !mobile || !message || !captcha || !captchaQuestion || message.length < 10) {
      return NextResponse.json(
        { error: 'All required fields must be filled' },
        { status: 400 }
      );
    }

    // Never trust the browser's captcha result. Recalculate the answer on the
    // server from the exact question that was displayed to the applicant.
    // Allow normal whitespace variations (for example, multiple spaces or a
    // line break) while keeping the expression deliberately limited to the
    // arithmetic expression generated by the form.
    if (!verifyMathCaptcha(captcha, captchaQuestion)) {
      return NextResponse.json({ error: 'Invalid security verification' }, { status: 400 });
    }

    // Validate email format
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailPattern.test(email)) {
      return NextResponse.json(
        { error: 'Invalid email format' },
        { status: 400 }
      );
    }

    // Validate resume file if provided
    if (resume) {
      const allowedTypes = ['application/pdf', 'application/msword', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'];
      if (!allowedTypes.includes(resume.type)) {
        return NextResponse.json(
          { error: 'Please upload a PDF, DOC, or DOCX file' },
          { status: 400 }
        );
      }
      
      if (resume.size > 5 * 1024 * 1024) {
        return NextResponse.json(
          { error: 'File size must be less than 5MB' },
          { status: 400 }
        );
      }
      if (!resume.name || /[\\/\0]/.test(resume.name)) return NextResponse.json({ error: 'Invalid file name' }, { status: 400 });
    }

    const db = getD1Client();
    const resumeKey = resume ? `resumes/${crypto.randomUUID()}-${resume.name.replace(/[^a-zA-Z0-9._-]/g, '_').slice(0, 180)}` : null;
    if (resume && resumeKey) await r2Client.upload(resumeKey, new Uint8Array(await resume.arrayBuffer()), resume.type);
    await db.prepare('INSERT INTO career_applications (id, fullname, email, mobile, city, message, resume_key) VALUES (?, ?, ?, ?, ?, ?, ?)')
      .bind(crypto.randomUUID(), fullname, email, mobile, city, message, resumeKey).run();

    // Prepare email content
    const htmlContent = renderSubmissionEmail({
      title: 'New Career Application',
      intro: 'A new career application has been received.',
      fields: [
        { label: 'Name', value: fullname },
         { label: 'Email', value: email, link: `<a href="mailto:${escapeHtml(email)}" style="color:#b48600">${escapeHtml(email)}</a>` },
         { label: 'Phone', value: mobile, link: `<a href="tel:${escapeHtml(mobile)}" style="color:#b48600">${escapeHtml(mobile)}</a>` },
        { label: 'City', value: city },
      ],
      message,
    });

    // Send email to admin
    const mailOptions: any = {
      from: getMailConfig().from,
      to: getMailConfig().to,
      subject: `New Career Application: ${fullname}`,
      html: htmlContent,
      replyTo: email,
    };

    // Attach resume if provided
    if (resume) {
      const buffer = Buffer.from(await resume.arrayBuffer());
      mailOptions.attachments = [{
        filename: resume.name,
        content: buffer,
        contentType: resume.type,
      }];
    }

    await getMailer().sendMail(mailOptions);

    // Send confirmation email to applicant
    await getMailer().sendMail({
      from: getMailConfig().from,
      to: email,
      subject: 'Thank you for your application - Sahil Industries',
      html: `
        <!DOCTYPE html>
        <html>
        <head>
          <meta charset="utf-8">
          <meta name="viewport" content="width=device-width, initial-scale=1.0">
        </head>
        <body style="font-family: Arial, sans-serif; line-height: 1.6; color: #333; max-width: 600px; margin: 0 auto; padding: 20px;">
          <div style="background: linear-gradient(135deg, #f6c515 0%, #e6b314 100%); padding: 30px; border-radius: 10px 10px 0 0; text-align: center;">
            <h1 style="color: #0c131a; margin: 0; font-size: 24px;">Thank You for Applying!</h1>
          </div>
          <div style="background: #f9f9f9; padding: 30px; border-radius: 0 0 10px 10px; border: 1px solid #eee;">
             <p style="font-size: 16px; color: #333;">Dear ${escapeHtml(fullname)},</p>
            <p style="color: #555;">We have received your career application and will review it shortly. Our team will contact you if your profile matches our requirements.</p>
            <div style="background: white; padding: 20px; border-radius: 8px; margin: 20px 0; border-left: 4px solid #f6c515;">
              <p style="margin: 0; color: #666;"><strong>Your application summary:</strong></p>
              <p style="margin: 10px 0 0; color: #333;">Position: General Application</p>
            </div>
            <p style="color: #555;">For immediate assistance, you can also call us at <a href="tel:+919623242324" style="color: #f6c515;">+91 96 2324 2324</a> or email us at <a href="mailto:sahilcranes@gmail.com" style="color: #f6c515;">sahilcranes@gmail.com</a>.</p>
            <hr style="border: none; border-top: 1px solid #ddd; margin: 20px 0;">
            <p style="color: #888; font-size: 12px; margin: 0; text-align: center;">
              Sahil Industries<br>
              Plot No. B 88, 89, 90 Kagal Hatkanagale Five Star MIDC,<br>
              Village – Halsawade, Tal.- Karveer, Dist.- Kolhapur - 416 236
            </p>
          </div>
        </body>
        </html>
      `,
    });

    return NextResponse.json(
      { message: 'Application submitted successfully' },
      { status: 200 }
    );
  } catch (error) {
    console.error('Career form error:', error);
    // Return more specific error message
    const errorMessage = error instanceof Error ? error.message : 'Unknown error';
    return NextResponse.json(
      { error: `Failed to submit application: ${errorMessage}` },
      { status: 500 }
    );
  }
}

